-- Corde — more than one secret code (after secret.sql). Each code opens its own group of hidden songs, and only that
-- group: a song is in one group or in none (songs.secret_group), so the codes never mix with each other or with the
-- library. The first code (secret.sql) becomes group 1. A hidden song without a group shows up for nobody.
-- The admin names the groups (the name is the tab the players see), makes new codes and moves songs from the panel.

create table if not exists public.secret_groups (
  id         int generated by default as identity primary key,
  name       text not null check (char_length(name) between 1 and 30),
  code_hash  text not null unique,
  created_at timestamptz not null default now()
);
alter table public.secret_groups enable row level security;
revoke all on public.secret_groups from public, anon, authenticated;

insert into public.secret_groups (id, name, code_hash)
select 1, 'Secretas', c.code_hash from public.secret_config c where c.id = 1
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.secret_groups', 'id'), greatest(1, (select max(id) from public.secret_groups)));

alter table public.songs add column if not exists secret_group int references public.secret_groups (id) on delete set null;
update public.songs set secret_group = 1 where hidden and secret_group is null;
-- the songs that count for the kittens (the notes that are cats: src/achievements.js "coro-gatitos")
alter table public.songs add column if not exists miau boolean not null default false;

-- the group a code opens (null: none; a wrong guess waits a little, so guessing is slow). A phone writes the
-- apostrophe curly (’): the codes read the same either way
create or replace function public.secret_group_of(p_code text) returns int
language plpgsql security definer set search_path = public as $$
declare g int; c text := lower(btrim(translate(coalesce(p_code, ''), chr(8217) || chr(8216) || chr(96) || chr(180) || chr(8220) || chr(8221), repeat(chr(39), 4) || repeat(chr(34), 2))));
begin
  select id into g from secret_groups where code_hash = encode(sha256(convert_to(c, 'UTF8')), 'hex');
  if g is null then perform pg_sleep(0.6); end if;
  return g;
end $$;
revoke all on function public.secret_group_of(text) from public, anon, authenticated;

create or replace function public.secret_ok(p_code text) returns boolean
language sql security definer set search_path = public as $$ select secret_group_of(p_code) is not null $$;
revoke all on function public.secret_ok(text) from public, anon, authenticated;

-- A code's songs (what the game asks now) → { id, name, songs: [...] }
create or replace function public.secret_open(p_code text) returns json
language plpgsql security definer set search_path = public as $$
declare g secret_groups;
begin
  select * into g from secret_groups where id = secret_group_of(p_code);
  if g.id is null then raise exception 'Código incorrecto' using errcode = '28000'; end if;
  return json_build_object('id', g.id, 'name', g.name, 'songs',
    coalesce((select json_agg(s order by s.artist, s.name) from songs s where s.hidden and s.secret_group = g.id), '[]'::json));
end $$;

-- the same songs, as browsers from before the groups ask for them
create or replace function public.secret_songs(p_code text) returns setof public.songs
language plpgsql security definer set search_path = public as $$
declare g int := secret_group_of(p_code);
begin
  if g is null then raise exception 'Código incorrecto' using errcode = '28000'; end if;
  return query select * from songs where hidden and secret_group = g order by artist, name;
end $$;

-- a hidden song's board, for whoever has its group's code
create or replace function public.secret_board(p_code text, p_song_id text, p_diff text, p_lanes int, p_limit int default 1000)
returns table (name text, score int, acc real, max_combo int)
language plpgsql security definer set search_path = public as $$
declare g int := secret_group_of(p_code);
begin
  if g is null then raise exception 'Código incorrecto' using errcode = '28000'; end if;
  return query
    select b.name, b.score::int, b.acc::real, b.max_combo::int from board_song b
    join songs s on s.id = b.song_id and s.hidden and s.secret_group = g
    where b.song_id = p_song_id and b.diff = p_diff and b.lanes = p_lanes
    order by b.score desc, b.updated_at limit least(greatest(coalesce(p_limit, 1000), 1), 1000);
end $$;

revoke all on function public.secret_open(text), public.secret_songs(text), public.secret_board(text, text, text, int, int) from public, anon, authenticated;
grant execute on function public.secret_open(text), public.secret_songs(text), public.secret_board(text, text, text, int, int) to anon, authenticated;

